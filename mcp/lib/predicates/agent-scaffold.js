// agent-scaffold.js
//
// Shared agent-scaffold predicate library for codex-cli + chat-claude-code
// (and any future agent-runtime connector whose session log inlines framing
// turns as if they were user-typed).
//
// Background (F-CROSS-AGENT-SCAFFOLD-PREDICATE, cross-source):
//   Agent runtimes (Codex, chat-claude-code, future Anthropic-style agents)
//   inject "scaffold" turns into the session log as if they were typed by
//   the operator. These turns look like user messages but are actually the
//   harness conditioning the next assistant turn:
//
//       <system_prompt>...</system_prompt>
//       <goal_context>...</goal_context>
//       <subagent_notification>...</subagent_notification>
//       <environment_context>...</environment_context>
//       <INSTRUCTIONS>...</INSTRUCTIONS>
//       <thesis_statement>...</thesis_statement>
//       <counterpart_gaps>...</counterpart_gaps>
//       # AGENTS.md instructions for <repo>
//       CONTEXT AND INSTRUCTIONS:
//
//   Each agent connector had its own copy of the regex (codex-cli ships one;
//   chat-claude-code will replicate it once the connector reads transcripts).
//   Duplicated regexes drift: a new scaffold token gets added in one source
//   and the other silently leaks the row.
//
//   This module is the single source of truth.
//
// Contract:
//
//   The PRIMARY signal is connector-side `raw_content.auto_injected = true`
//   stamped at write-time. The connector is the only thing that can know for
//   sure whether a turn was generated by the harness vs typed by the
//   operator. Tagging at write-time also avoids re-running the regex on
//   every Stage-0 dispatch.
//
//   This regex is the FALLBACK for unflagged historical rows already on
//   disk (and for connectors that have not yet wired the auto_injected
//   flag). It is anchored at `^\s*` so a real operator message that merely
//   DISCUSSES one of these tokens ("the <system_prompt> tag worked great")
//   does NOT match.
//
// Critic-modified contract (per node critic_modifications):
//   * Connector-side flag is primary; regex is fallback.
//   * Stage-0 callers should quarantine (not permanently drop) — 14-day
//     retention so a false-positive scaffold-shaped operator turn is
//     recoverable.
//   * Apply persona_replay_dedup keyed by (system_prompt_hash, day) to
//     suppress repeats of the same harness boot.
//
// ES module. No external dependencies. Safe to import from Stage-0 rules,
// connector writers, salience policy, and operator audit tools.

// ---------------------------------------------------------------------------
// SCAFFOLD_USER_RE
// ---------------------------------------------------------------------------
//
// Anchored at start-of-string with `^\s*` so the scaffold token must be the
// FIRST non-whitespace content of the turn. Case-insensitive so future
// connectors emitting `<System_Prompt>` (Title-Case) still match.
//
// The alternatives are organised as:
//   * Angle-bracket harness tags (with `\b` after the tag name so a longer
//     extension like `<system_prompts>` does not match the `<system_prompt>`
//     alternative by accident).
//   * `# AGENTS.md instructions for ...` — the codex/claude AGENTS.md
//     auto-injection header.
//   * `CONTEXT AND INSTRUCTIONS:` — the chat-claude-code style framing.
//
// IMPORTANT: keep in sync with the connector-side SCAFFOLD_USER_RE in
// lib/connectors/codex-cli.js (and any future chat-claude-code connector).
// The cross-connector regression test (F-T1-CODEX_CLI-F1) asserts parity
// across all importers.
// ---------------------------------------------------------------------------
export const SCAFFOLD_USER_RE =
  /^\s*(?:<(?:environment_context|system_prompt|goal_context|subagent_notification|INSTRUCTIONS|thesis_statement|counterpart_gaps)\b|# AGENTS\.md instructions for|CONTEXT AND INSTRUCTIONS:)/i;

// ---------------------------------------------------------------------------
// Default quarantine retention for scaffold-dropped rows. Per critic
// guidance: false-positive scaffold-shaped operator turns are recoverable
// for 14 days before purge. The Stage-0 caller stamps this on the
// quarantine entry's rule_id so the purge tool can surface "kept 14d".
// ---------------------------------------------------------------------------
export const SCAFFOLD_RETENTION_DAYS = 14;

// ---------------------------------------------------------------------------
// looksAutoInjectedUserText(userText)
//
// Returns true iff `userText` matches the scaffold-prefix regex. Pure
// predicate; no side effects.
//
// Non-string / empty inputs return false (defensive — callers occasionally
// pass `undefined` from a missing user_text field).
// ---------------------------------------------------------------------------
export function looksAutoInjectedUserText(userText) {
  if (typeof userText !== "string" || userText.length === 0) return false;
  return SCAFFOLD_USER_RE.test(userText);
}

// ---------------------------------------------------------------------------
// isAgentScaffoldTurn(row)
//
// Composite classifier — accepts a row envelope and returns a structured
// verdict the caller uses to choose between DROP+quarantine and PASS.
//
// Input shape (the union of fields the agent-runtime connectors emit):
//   {
//     user_text?:   string
//     raw_content?: {
//       user_text?:     string
//       auto_injected?: boolean   // PRIMARY signal — connector write-time flag
//     }
//   }
//
// Output:
//   {
//     scaffold:          bool,
//     trigger:           'flag' | 'regex' | null,
//     suggested_action:  'DROP' | 'PASS',
//   }
//
// Decision table:
//   raw_content.auto_injected === true  -> {scaffold:true, trigger:'flag',  DROP}
//   regex matches user_text             -> {scaffold:true, trigger:'regex', DROP}
//   neither                             -> {scaffold:false, trigger:null,   PASS}
//
// The Stage-0 caller still owns the quarantine decision and the
// assistant-text-empty gating per source (codex-cli drops only when there
// is no assistant_text; chat-claude-code may apply a different rule).
// ---------------------------------------------------------------------------
function _pickUserText(row) {
  if (!row || typeof row !== "object") return "";
  if (typeof row.user_text === "string" && row.user_text.length > 0) {
    return row.user_text;
  }
  const rc = row.raw_content;
  if (rc && typeof rc === "object") {
    if (typeof rc.user_text === "string" && rc.user_text.length > 0) {
      return rc.user_text;
    }
  }
  return "";
}

function _pickAutoInjectedFlag(row) {
  if (!row || typeof row !== "object") return false;
  if (row.auto_injected === true) return true;
  const rc = row.raw_content;
  if (rc && typeof rc === "object" && rc.auto_injected === true) return true;
  return false;
}

export function isAgentScaffoldTurn(row) {
  if (_pickAutoInjectedFlag(row)) {
    return { scaffold: true, trigger: "flag", suggested_action: "DROP" };
  }
  const userText = _pickUserText(row);
  if (looksAutoInjectedUserText(userText)) {
    return { scaffold: true, trigger: "regex", suggested_action: "DROP" };
  }
  return { scaffold: false, trigger: null, suggested_action: "PASS" };
}

export default {
  SCAFFOLD_USER_RE,
  SCAFFOLD_RETENTION_DAYS,
  looksAutoInjectedUserText,
  isAgentScaffoldTurn,
};
